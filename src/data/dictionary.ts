/** Excepciones a las reglas regulares */
type Opts = {
  pl?: string; // plural inglés irregular (feet, teeth…)
  esPl?: string; // plural español irregular
  u?: true; // incontable: no tiene plural (water, rice…)
  pair?: true; // siempre plural en inglés (pants, glasses…)
  past?: string; // pasado irregular (verbos)
  pres?: string; // presente irregular (be)
  third?: string; // he / she / it irregular
  one?: true; // normalmente sólo tienes uno: no se genera frase en plural
  np?: true; // no se usa en plural (meses, hoy…) pero no es "incontable"
  ex?: [en: string, es: string]; // frase de ejemplo escrita a mano
  note?: string;
};

