/* ---------- Forma derivada de cada palabra ---------- */

export type Entry = {
  id: string;
  en: string;
  es: string;
  kind: Kind;
  /** frases listas para mostrar */
  singEn: string;
  singEs: string;
  plEn: string | null;
  plEs: string | null;
  enPl: string;
  esPl: string;
  uncountable: boolean;
  noPlural: boolean;
  pair: boolean;
  one: boolean;
  ex?: Sentence;
  third?: string;
  past?: string;
  note?: string;
};

function regularPast(v: string) {
  if (v.endsWith("e")) return v + "d";
  if (/[^aeiou]y$/.test(v)) return v.slice(0, -1) + "ied";
  return v + "ed";
}

function buildEntry(topic: TopicDef, [en, es, o = {}]: Row, i: number): Entry {
  const id = `${topic.slug}-${i}`;
  const base = {
    id,
    en,
    es,
    kind: topic.kind,
    note: o.note,
    uncountable: !!o.u,
    noPlural: !!o.np,
    pair: !!o.pair,
    one: !!o.one,
    ex: o.ex ? { en: o.ex[0], es: o.ex[1] } : undefined,
  };

  if (topic.kind === "verb") {
    const third = o.third ?? thirdPersonEn(en);
    return {
      ...base,
      singEn: o.pres ?? `I ${en} · you ${en}`,
      singEs: es,
      plEn: `he ${third} · she ${third}`,
      plEs: null,
      enPl: en,
      esPl: es,
      third,
      past: o.past ?? regularPast(en),
    };
  }

  if (topic.kind === "adj") {
    const esPl = o.esPl ?? pluralEsAdj(es);
    return { ...base, singEn: en, singEs: es, plEn: en, plEs: esPl, enPl: en, esPl };
  }

  const hasArticle = /^(el|la|los|las) /.test(es);
  const esPl = o.esPl ?? (o.u || o.np ? es : hasArticle ? pluralEs(es) : es);

  if (o.pair) {
    // si en español ya es plural (los lentes) se cuentan "pares"
    const esIsPlural = /^(los|las) /.test(es);
    return {
      ...base,
      singEn: `a pair of ${en}`,
      singEs: indefiniteEs(es),
      plEn: `two pairs of ${en}`,
      plEs: esIsPlural ? `dos pares de ${bareEs(esPl)}` : `dos ${bareEs(esPl)}`,
      enPl: en,
      esPl,
    };
  }

  if (o.u || o.np) {
    return { ...base, singEn: en, singEs: es, plEn: null, plEs: null, enPl: en, esPl };
  }

  const enPl = o.pl ?? pluralEn(en);
  return {
    ...base,
    singEn: `${indefiniteEn(en)} ${en}`,
    singEs: hasArticle ? indefiniteEs(es) : es,
    plEn: enPl,
    plEs: esPl,
    enPl,
    esPl,
  };
}

/** Rellena una frase modelo con las formas de una palabra */
function fill(tpl: string, e: Entry) {
  const first = (s: string) => s.split(" / ")[0].replace(/\s*\(.*?\)/, "");
  const firstEs = first(e.es);
  const firstEsPl = first(e.esPl);
  const fem = /^(la|las) /.test(firstEs) || /^las /.test(firstEsPl);
  const tokens: Record<string, string> = {
    en: e.en,
    enPl: e.enPl,
    a: e.uncountable || e.noPlural ? e.en : e.singEn,
    es: firstEs,
    esPl: firstEsPl,
    esN: bareEs(firstEs),
    esNPl: bareEs(firstEsPl),
    un: e.uncountable || e.noPlural ? firstEs : indefiniteEs(firstEs),
    unos: indefiniteEs(firstEsPl),
    este: fem ? "esta" : "este",
    estos: fem ? "estas" : "estos",
  };
  const out = tpl.replace(/\{(\w)(\w*)\}/g, (_, first: string, rest: string) => {
    const key = first.toLowerCase() + rest;
    const val = tokens[key] ?? "";
    return first === first.toUpperCase() ? capitalize(val) : val;
  });
  return capitalize(out);
}

export type Sentence = { en: string; es: string };

export type Topic = Omit<TopicDef, "rows" | "questions" | "sing" | "plural"> & {
  entries: Entry[];
  questions: { q: string; qEs: string; a: string; aEs: string }[];
  /** frases de ejemplo para una palabra (singular y plural) */
  examples: (e: Entry) => { sing?: Sentence; plural?: Sentence };
};

export const DICTIONARY: Topic[] = TOPICS.map((t) => ({
  slug: t.slug,
  title: t.title,
  titleEn: t.titleEn,
  emoji: t.emoji,
  color: t.color,
  kind: t.kind,
  blurb: t.blurb,
  entries: t.rows.map((r, i) => buildEntry(t, r, i)),
  questions: t.questions.map(([q, qEs, a, aEs]) => ({ q, qEs, a, aEs })),
  examples: (e) => {
    const sing = e.ex ?? (t.sing && !e.pair ? { en: fill(t.sing[0], e), es: fill(t.sing[1], e) } : undefined);
    const plural =
      t.plural && !e.pair && !e.one && !e.uncountable && !e.noPlural
        ? { en: fill(t.plural[0], e), es: fill(t.plural[1], e) }
        : undefined;
    return { sing, plural };
  },
}));

export const topicBySlug = (slug: string) => DICTIONARY.find((t) => t.slug === slug);

export const TOTAL_WORDS = DICTIONARY.reduce((n, t) => n + t.entries.length, 0);

/** Frases para el juego de bloques: preguntas, respuestas y ejemplos del tema */
export function builderSentences(topic: Topic): Sentence[] {
  const fromQuestions = topic.questions.flatMap((q) => [
    { en: q.q, es: q.qEs },
    { en: q.a, es: q.aEs },
  ]);
  const fromWords = topic.entries.flatMap((e) => {
    const ex = topic.examples(e);
    return [ex.sing, ex.plural].filter((s): s is Sentence => !!s);
  });
  return [...fromQuestions, ...fromWords];
}

export function searchDictionary(query: string, limit = 8) {
  const q = query
    .trim()
    .toLowerCase()
    .normalize("NFD")
    .replace(/[̀-ͯ]/g, "");
  if (q.length < 2) return [];
  const norm = (s: string) => s.toLowerCase().normalize("NFD").replace(/[̀-ͯ]/g, "");
  const results: { topic: Topic; entry: Entry; score: number }[] = [];
  for (const topic of DICTIONARY) {
    for (const entry of topic.entries) {
      const en = norm(entry.en);
      const es = norm(entry.es);
      const score =
        en === q || bareEs(es) === q ? 0 : en.startsWith(q) || bareEs(es).startsWith(q) ? 1 : en.includes(q) || es.includes(q) ? 2 : -1;
      if (score >= 0) results.push({ topic, entry, score });
    }
  }
  return results.sort((a, b) => a.score - b.score).slice(0, limit);
}
